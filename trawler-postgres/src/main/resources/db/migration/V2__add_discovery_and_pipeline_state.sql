CREATE TABLE IF NOT EXISTS discovery_checkpoints (
    pipeline_id VARCHAR(255) NOT NULL,
    discovery_id VARCHAR(255) NOT NULL,
    revision BIGINT NOT NULL,
    codec_id VARCHAR(255) NOT NULL,
    codec_version INTEGER NOT NULL,
    payload BYTEA NOT NULL,
    generation_id VARCHAR(255),
    strategy_id VARCHAR(255),
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (pipeline_id, discovery_id),
    CONSTRAINT discovery_checkpoints_revision_check CHECK (revision >= 0),
    CONSTRAINT discovery_checkpoints_codec_version_check CHECK (codec_version >= 0)
);

CREATE TABLE IF NOT EXISTS discovery_checkpoint_quarantine (
    quarantine_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_id VARCHAR(255) NOT NULL,
    discovery_id VARCHAR(255) NOT NULL,
    revision BIGINT NOT NULL,
    codec_id VARCHAR(255) NOT NULL,
    codec_version INTEGER NOT NULL,
    payload BYTEA NOT NULL,
    generation_id VARCHAR(255),
    strategy_id VARCHAR(255),
    completed BOOLEAN NOT NULL,
    reason VARCHAR(4096) NOT NULL,
    quarantined_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT discovery_checkpoint_quarantine_revision_check CHECK (revision >= 0),
    CONSTRAINT discovery_checkpoint_quarantine_codec_version_check CHECK (codec_version >= 0)
);

CREATE INDEX IF NOT EXISTS discovery_checkpoint_quarantine_lookup_idx
    ON discovery_checkpoint_quarantine (pipeline_id, discovery_id, quarantined_at);

CREATE TABLE IF NOT EXISTS harvest_state (
    pipeline_id VARCHAR(255) NOT NULL,
    strategy_id VARCHAR(255) NOT NULL,
    revision BIGINT NOT NULL,
    codec_id VARCHAR(255) NOT NULL,
    codec_version INTEGER NOT NULL,
    payload BYTEA NOT NULL,
    historical_complete BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (pipeline_id, strategy_id),
    CONSTRAINT harvest_state_revision_check CHECK (revision >= 0),
    CONSTRAINT harvest_state_codec_version_check CHECK (codec_version >= 0)
);

CREATE TABLE IF NOT EXISTS harvest_state_quarantine (
    quarantine_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_id VARCHAR(255) NOT NULL,
    strategy_id VARCHAR(255) NOT NULL,
    revision BIGINT NOT NULL,
    codec_id VARCHAR(255) NOT NULL,
    codec_version INTEGER NOT NULL,
    payload BYTEA NOT NULL,
    historical_complete BOOLEAN NOT NULL,
    reason VARCHAR(4096) NOT NULL,
    quarantined_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT harvest_state_quarantine_revision_check CHECK (revision >= 0),
    CONSTRAINT harvest_state_quarantine_codec_version_check CHECK (codec_version >= 0)
);

CREATE INDEX IF NOT EXISTS harvest_state_quarantine_lookup_idx
    ON harvest_state_quarantine (pipeline_id, strategy_id, quarantined_at);

CREATE TABLE IF NOT EXISTS pipeline_health (
    pipeline_id VARCHAR(255) PRIMARY KEY,
    revision BIGINT NOT NULL,
    consecutive_failures INTEGER NOT NULL DEFAULT 0,
    total_successes BIGINT NOT NULL DEFAULT 0,
    total_failures BIGINT NOT NULL DEFAULT 0,
    last_observed_at TIMESTAMPTZ,
    circuit_open_until TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pipeline_health_revision_check CHECK (revision >= 0),
    CONSTRAINT pipeline_health_consecutive_failures_check CHECK (consecutive_failures >= 0),
    CONSTRAINT pipeline_health_total_successes_check CHECK (total_successes >= 0),
    CONSTRAINT pipeline_health_total_failures_check CHECK (total_failures >= 0)
);

CREATE TABLE IF NOT EXISTS pipeline_overrides (
    pipeline_id VARCHAR(255) PRIMARY KEY,
    enabled BOOLEAN NOT NULL,
    reason VARCHAR(4096),
    expires_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL
);
