CREATE SEQUENCE IF NOT EXISTS lease_token_sequence;
CREATE SEQUENCE IF NOT EXISTS attempt_sequence;

CREATE TABLE IF NOT EXISTS engine_runs (
    engine_run_id VARCHAR(255) PRIMARY KEY,
    status VARCHAR(16) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    last_observed_at TIMESTAMPTZ NOT NULL,
    reason VARCHAR(4096),
    recovery_reason VARCHAR(4096),
    failure_count BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT engine_runs_status_check CHECK (status IN ('RUNNING', 'COMPLETED', 'ABANDONED', 'FAILED', 'CANCELLED')),
    CONSTRAINT engine_runs_failure_count_check CHECK (failure_count >= 0)
);

CREATE INDEX IF NOT EXISTS engine_runs_stale_idx
    ON engine_runs (last_observed_at)
    WHERE status = 'RUNNING';

CREATE TABLE IF NOT EXISTS pipeline_runs (
    pipeline_run_id VARCHAR(255) PRIMARY KEY,
    engine_run_id VARCHAR(255) NOT NULL REFERENCES engine_runs (engine_run_id) ON DELETE CASCADE,
    pipeline_id VARCHAR(255) NOT NULL,
    status VARCHAR(16) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    last_observed_at TIMESTAMPTZ NOT NULL,
    recovery_reason VARCHAR(4096),
    failure_count BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pipeline_runs_status_check CHECK (status IN ('RUNNING', 'COMPLETED', 'ABANDONED', 'FAILED', 'CANCELLED')),
    CONSTRAINT pipeline_runs_failure_count_check CHECK (failure_count >= 0),
    CONSTRAINT pipeline_runs_engine_pipeline_unique UNIQUE (engine_run_id, pipeline_id)
);

CREATE INDEX IF NOT EXISTS pipeline_runs_stale_idx
    ON pipeline_runs (last_observed_at)
    WHERE status = 'RUNNING';

CREATE TABLE IF NOT EXISTS resources (
    resource_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_id VARCHAR(255) NOT NULL,
    identity_value VARCHAR(4096) NOT NULL,
    last_completed_at TIMESTAMPTZ,
    next_eligible_at TIMESTAMPTZ,
    visit_count BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT resources_visit_count_check CHECK (visit_count >= 0),
    CONSTRAINT resources_pipeline_identity_unique UNIQUE (pipeline_id, identity_value)
);

CREATE TABLE IF NOT EXISTS jobs (
    job_id VARCHAR(255) PRIMARY KEY,
    pipeline_id VARCHAR(255) NOT NULL,
    resource_id BIGINT NOT NULL REFERENCES resources (resource_id) ON DELETE RESTRICT,
    request_codec_id VARCHAR(255) NOT NULL,
    request_codec_version INTEGER NOT NULL,
    request_payload BYTEA NOT NULL,
    status VARCHAR(16) NOT NULL,
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    enqueued_at TIMESTAMPTZ NOT NULL,
    not_before TIMESTAMPTZ,
    lease_token VARCHAR(255),
    lease_owner VARCHAR(255),
    lease_expires_at TIMESTAMPTZ,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    active_attempt_id VARCHAR(255),
    finished_at TIMESTAMPTZ,
    reason VARCHAR(4096),
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT jobs_status_check CHECK (status IN ('QUEUED', 'LEASED', 'RETRY_WAIT', 'SUCCEEDED', 'FAILED', 'SKIPPED', 'CANCELLED', 'ABANDONED')),
    CONSTRAINT jobs_codec_version_check CHECK (request_codec_version >= 0),
    CONSTRAINT jobs_attempt_count_check CHECK (attempt_count >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS jobs_one_active_resource_idx
    ON jobs (resource_id)
    WHERE status IN ('QUEUED', 'LEASED', 'RETRY_WAIT');

CREATE INDEX IF NOT EXISTS jobs_claim_idx
    ON jobs (pipeline_id, status, not_before, sequence);

CREATE INDEX IF NOT EXISTS jobs_lease_expiry_idx
    ON jobs (lease_expires_at)
    WHERE status = 'LEASED';

CREATE TABLE IF NOT EXISTS attempts (
    attempt_id VARCHAR(255) PRIMARY KEY,
    job_id VARCHAR(255) NOT NULL REFERENCES jobs (job_id) ON DELETE RESTRICT,
    pipeline_id VARCHAR(255) NOT NULL,
    attempt_number INTEGER NOT NULL,
    lease_token VARCHAR(255) NOT NULL,
    lease_owner VARCHAR(255) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    outcome VARCHAR(16),
    reason VARCHAR(4096),
    CONSTRAINT attempts_number_check CHECK (attempt_number > 0),
    CONSTRAINT attempts_outcome_check CHECK (outcome IS NULL OR outcome IN ('SUCCEEDED', 'FAILED', 'CANCELLED', 'ABANDONED')),
    CONSTRAINT attempts_job_number_unique UNIQUE (job_id, attempt_number)
);

CREATE INDEX IF NOT EXISTS attempts_job_idx ON attempts (job_id, attempt_number);
